<?php

namespace App\Http\Controllers;

use Illuminate\Http\Request;

/*
|--------------------------------------------------------------------------
| Load FPDF manually
|--------------------------------------------------------------------------
*/

require_once base_path('vendor/setasign/fpdi/fpdf.php');

use setasign\Fpdi\Fpdi;

class RotatePdfController extends Controller
{
    /*
    |--------------------------------------------------------------------------
    | Show Rotate PDF Page
    |--------------------------------------------------------------------------
    */

    public function index()
    {
        return view('rotate-pdf');
    }


    /*
    |--------------------------------------------------------------------------
    | Rotate PDF
    |--------------------------------------------------------------------------
    */

    public function rotate(Request $request)
    {
        /*
        |--------------------------------------------------------------------------
        | Validation
        |--------------------------------------------------------------------------
        */

        $request->validate([
            'pdf' => 'required|file|mimes:pdf|max:20480',
            'angle' => 'required|integer|in:90,180,270',
        ]);


        $outputPath = null;


        try {

            /*
            |--------------------------------------------------------------------------
            | Uploaded PDF
            |--------------------------------------------------------------------------
            */

            $file = $request->file('pdf');

            $inputPath = $file->getRealPath();


            if (!$inputPath || !file_exists($inputPath)) {

                throw new \Exception(
                    'Uploaded PDF could not be found.'
                );
            }


            /*
            |--------------------------------------------------------------------------
            | Rotation Angle
            |--------------------------------------------------------------------------
            */

            $angle = (int) $request->input('angle');


            /*
            |--------------------------------------------------------------------------
            | Create FPDI
            |--------------------------------------------------------------------------
            */

            $pdf = new Fpdi();

            $pdf->SetAutoPageBreak(false);


            /*
            |--------------------------------------------------------------------------
            | Load Source PDF
            |--------------------------------------------------------------------------
            */

            $pageCount = $pdf->setSourceFile($inputPath);


            if ($pageCount < 1) {

                throw new \Exception(
                    'The uploaded PDF does not contain any pages.'
                );
            }


            /*
            |--------------------------------------------------------------------------
            | Process Every Page
            |--------------------------------------------------------------------------
            */

            for (
                $pageNumber = 1;
                $pageNumber <= $pageCount;
                $pageNumber++
            ) {

                /*
                |--------------------------------------------------------------------------
                | Import Original Page
                |--------------------------------------------------------------------------
                */

                $templateId =
                    $pdf->importPage($pageNumber);


                /*
                |--------------------------------------------------------------------------
                | Get Original Page Size
                |--------------------------------------------------------------------------
                */

                $size =
                    $pdf->getTemplateSize($templateId);


                $width =
                    (float) $size['width'];

                $height =
                    (float) $size['height'];


                /*
                |--------------------------------------------------------------------------
                | Determine Orientation
                |--------------------------------------------------------------------------
                */

                $orientation =
                    $width > $height
                        ? 'L'
                        : 'P';


                /*
                |--------------------------------------------------------------------------
                | IMPORTANT
                |--------------------------------------------------------------------------
                |
                | FPDF supports page rotation directly.
                |
                | This rotates the PDF page itself instead of
                | rotating the template inside a new page.
                |
                | Therefore the original content is NOT cut.
                |
                |--------------------------------------------------------------------------
                */

                $pdf->AddPage(
                    $orientation,
                    [$width, $height],
                    $angle
                );


                /*
                |--------------------------------------------------------------------------
                | Place Original Page
                |--------------------------------------------------------------------------
                */

                $pdf->useTemplate(
                    $templateId,
                    0,
                    0,
                    $width,
                    $height
                );
            }


            /*
            |--------------------------------------------------------------------------
            | Output File Name
            |--------------------------------------------------------------------------
            */

            $fileName =
                'rotated-pdf-' .
                date('Ymd-His') .
                '.pdf';


            /*
            |--------------------------------------------------------------------------
            | Storage Directory
            |--------------------------------------------------------------------------
            */

            $storagePath =
                storage_path('app');


            if (!is_dir($storagePath)) {

                mkdir(
                    $storagePath,
                    0777,
                    true
                );
            }


            /*
            |--------------------------------------------------------------------------
            | Output Path
            |--------------------------------------------------------------------------
            */

            $outputPath =
                $storagePath .
                DIRECTORY_SEPARATOR .
                $fileName;


            /*
            |--------------------------------------------------------------------------
            | Create PDF
            |--------------------------------------------------------------------------
            */

            $pdf->Output(
                $outputPath,
                'F'
            );


            /*
            |--------------------------------------------------------------------------
            | Verify Output
            |--------------------------------------------------------------------------
            */

            if (
                !file_exists($outputPath) ||
                filesize($outputPath) <= 0
            ) {

                throw new \Exception(
                    'Rotated PDF could not be created.'
                );
            }


            /*
            |--------------------------------------------------------------------------
            | Download
            |--------------------------------------------------------------------------
            */

            return response()
                ->download(
                    $outputPath,
                    $fileName
                )
                ->deleteFileAfterSend(true);


        } catch (\Throwable $e) {

            /*
            |--------------------------------------------------------------------------
            | Cleanup
            |--------------------------------------------------------------------------
            */

            if (
                $outputPath &&
                file_exists($outputPath)
            ) {

                @unlink($outputPath);
            }


            /*
            |--------------------------------------------------------------------------
            | Show Error
            |--------------------------------------------------------------------------
            */

            return back()->withErrors([
                'pdf' =>
                    'PDF rotation failed: ' .
                    $e->getMessage()
            ]);
        }
    }
}